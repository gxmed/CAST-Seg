"""
Export dense CAM priors generated by Text-guided Semantic Localization (TSL).

Purpose
-------
This script does NOT save red/blue/JET visualization images.
It saves machine-readable CAM maps for later semi-supervised training:

    out_dir/
    ├── npy/       # float32 [H, W], range 0~1, recommended for training
    ├── gray_png/  # single-channel 0~255 png, only for checking
    └── manifest.csv

Default split is all samples in Train.csv.
You can also export the labeled, unlabeled, or validation subset.


Output content
--------------
For every row in Train.csv, this script saves one CAM with the same basename and suffix as the original image under Images/.
The .npy file is float32 [H, W] in range [0, 1]. The gray PNG is only for checking.

Name rule
---------
The output filename is kept the same as the original image filename in Images/.
For example, if CSV Image is:

    mask_covid_2889.png

then the actual image path is:

    Train Set/Images/covid_2889.png

and this script saves:

    npy/covid_2889.npy
    gray_png/covid_2889.png

This matches the original image filename, not the mask filename.

Example
-------
Run from the TSL directory:

python export_tsl_cam.py ^
  --config ./configs/tsl_qata.yaml ^
  --ckpt ./save_model/tsl_qata.ckpt ^
  --out_dir "D:\\path\\to\\Train Set\\TSL_CAM"
"""

